import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest'
import { mount, flushPromises } from '@vue/test-utils'
import ProjectSecurity from '@/modules/supply-chain/components/ProjectSecurity.vue'
import { supplyChainApi, saveBlob } from '@/modules/supply-chain/api'
import { makeScI18n, report, findings, DIGEST } from './support'

vi.mock('@/modules/supply-chain/api', () => ({
  supplyChainApi: { projectSecurity: vi.fn(), versionSecurity: vi.fn(), rescan: vi.fn(), downloadSbom: vi.fn() },
  saveBlob: vi.fn(),
}))

const i18n    = makeScI18n()
const project = { id: 'p1', name: 'orders-api', slug: 'orders-api' }
const mounted = []

function summary(extra = {}) {
  return {
    region:   { id: 'r1', name: 'istanbul', data_location: 'TR' },
    policy:   { mode: 'enforce', max_critical: 0, max_high: null, only_fixable: true, require_scan: false, require_signature: true },
    pipeline: { sbom: true, scan: true, signing: true, admission: 'enforce' },
    versions: [
      { id: 'v2', number: 2, label: 'v2', build_status: 'ready', applicable: false, image_kind: null, image: null, report: null },
      { id: 'v1', number: 1, label: 'v1', build_status: 'ready', applicable: true, image_kind: 'built', image: report().image_ref, report: report() },
    ],
    deployments: [{ id: 'd1', status: 'active', version_id: 'v1', version_label: 'v1', created_at: '2026-10-10T09:00:00Z', report: report() }],
    overrides:   [{ id: 'o1', version_id: 'v1', username: 'root', reason: 'fix rolls out tonight', violations: [{ rule: 'critical' }], created_at: '2026-10-10T09:00:00Z' }],
    ...extra,
  }
}

async function mountSecurity(data = summary()) {
  supplyChainApi.projectSecurity.mockResolvedValue({ data: { data } })
  const w = mount(ProjectSecurity, { props: { project }, global: { plugins: [i18n] } })
  mounted.push(w)
  await flushPromises()
  return w
}

beforeEach(() => vi.clearAllMocks())
afterEach(() => { mounted.splice(0).forEach(w => w.unmount()); vi.useRealTimers() })

describe('ProjectSecurity', () => {
  it('summarizes the region policy', async () => {
    const w = await mountSecurity()
    const policy = w.find('[data-policy-summary]').text()

    expect(policy).toContain('Region istanbul')
    expect(policy).toContain('data location TR')
    expect(policy).toContain('enforced')
    expect(policy).toContain('Critical ≤ 0 · High ≤ no limit')
    expect(policy).toContain('fixable findings only')
    expect(policy).toContain('signature verified on deploy')
    expect(policy).toContain('Admission: enforce')
  })

  it('lists versions with SBOM, severity badges and signature', async () => {
    const w = await mountSecurity()

    const v1 = w.find('[data-version-row="v1"]')
    expect(v1.text()).toContain('…/runr-builds/orders-api:v1')
    expect(v1.text()).toContain('Built by RunR')
    expect(v1.text()).toContain('42 packages')
    expect(v1.find('[data-severity="critical"]').text()).toBe('C2')
    expect(v1.text()).toContain('signed')

    expect(w.find('[data-version-row="v2"]').text()).toContain('no image of its own to check')
  })

  it('shows deployed versions and overrides', async () => {
    const w = await mountSecurity()

    expect(w.find('[data-deployment-row="d1"]').text()).toContain('active')
    expect(w.find('[data-deployment-row="d1"] [data-severity="high"]').text()).toBe('H1')
    expect(w.find('[data-override="o1"]').text()).toContain('fix rolls out tonight')
    expect(w.find('[data-override="o1"]').text()).toContain('root')
    expect(w.find('[data-override="o1"]').text()).toContain('critical')
  })

  it('opens the version detail: findings, SBOM summary, signature and the deploy decision', async () => {
    supplyChainApi.versionSecurity.mockResolvedValue({ data: { data: {
      version: summary().versions[1],
      report:  { ...report(), findings, sbom_summary: { packages: 42, by_type: { deb: 30, pypi: 12 }, licenses: { MIT: 5 }, generator: 'syft-1.18.1' }, scanner: { version: '0.58.1', db_updated_at: '2026-10-10T06:00:00Z' }, sbom_formats: ['spdx-json', 'cyclonedx-json'] },
      decision: { applicable: true, blocked: true, violations: [{ rule: 'critical', message: '2 CRITICAL vulnerabilities (allowed: 0)', enforced: true }] },
    } } })
    const w = await mountSecurity()

    await w.find('[data-version-row="v1"] button').trigger('click')
    await flushPromises()

    const detail = w.find('[data-version-detail]')
    expect(supplyChainApi.versionSecurity).toHaveBeenCalledWith('p1', 'v1')
    expect(detail.text()).toContain(DIGEST)
    expect(detail.find('[data-decision]').text()).toContain('2 CRITICAL vulnerabilities (allowed: 0)')
    expect(detail.find('[data-sbom-summary]').text()).toContain('deb 30')
    expect(detail.find('[data-sbom-summary]').text()).toContain('MIT (5)')
    expect(detail.text()).toContain('Generated by syft-1.18.1')
    expect(detail.text()).toContain('Trivy 0.58.1')
    expect(detail.findAll('[data-finding]')).toHaveLength(3)
    expect(detail.text()).not.toContain('PRIVATE KEY')
  })

  it('labels a Spin app and explains why it has no SBOM or scan', async () => {
    const spin = { id: 'v3', number: 3, label: 'v3', build_status: 'ready', applicable: true, image_kind: 'wasm', image: report().image_ref,
      report: report({ sbom_status: 'skipped', referrer_status: 'skipped', scan_status: 'skipped', attestation_status: 'skipped', packages: null }) }
    supplyChainApi.versionSecurity.mockResolvedValue({ data: { data: {
      version: spin,
      report:  { ...spin.report, findings: [], sbom_summary: null, sbom_formats: [] },
      decision: { applicable: true, blocked: false, violations: [] },
    } } })
    const w = await mountSecurity(summary({ versions: [spin] }))

    expect(w.find('[data-version-row="v3"]').text()).toContain('Spin app (Wasm)')
    expect(w.find('[data-version-row="v3"]').text()).toContain('signed')

    await w.find('[data-version-row="v3"] button').trigger('click')
    await flushPromises()

    const detail = w.find('[data-version-detail]')
    expect(detail.find('[data-wasm-note]').text()).toContain('no container filesystem for syft and Trivy')
    expect(detail.findAll('[data-finding]')).toHaveLength(0)
  })

  it('downloads an SBOM', async () => {
    supplyChainApi.downloadSbom.mockResolvedValue({ data: new Blob(['{}']), headers: {} })
    const w = await mountSecurity()

    await w.find('[data-version-row="v1"] button[title^="Download SBOM"]').trigger('click')
    await flushPromises()

    expect(supplyChainApi.downloadSbom).toHaveBeenCalledWith('p1', 'v1', 'spdx-json')
    expect(saveBlob).toHaveBeenCalledWith(expect.anything(), 'orders-api-v1.spdx.json')
  })

  it('queues a scan and polls while it runs', async () => {
    vi.useFakeTimers()
    supplyChainApi.rescan.mockResolvedValue({ data: { data: { status: 'pending' } } })
    const w = await mountSecurity()

    const running = summary()
    running.versions[1].report = report({ status: 'pending', scan_status: 'pending' })
    supplyChainApi.projectSecurity.mockResolvedValue({ data: { data: running } })

    await w.find('[data-version-row="v1"] button[title="Scan again"]').trigger('click')
    await flushPromises()
    expect(supplyChainApi.rescan).toHaveBeenCalledWith('p1', 'v1')
    expect(w.find('[data-version-row="v1"] button[title="Scan again"]').attributes('disabled')).toBeDefined()

    supplyChainApi.projectSecurity.mockResolvedValue({ data: { data: summary() } })
    await vi.advanceTimersByTimeAsync(5000)
    await flushPromises()
    expect(supplyChainApi.projectSecurity).toHaveBeenCalledTimes(3)
    expect(w.find('[data-version-row="v1"] button[title="Scan again"]').attributes('disabled')).toBeUndefined()
  })

  it('a project without versions', async () => {
    const w = await mountSecurity(summary({ versions: [], deployments: [], overrides: [] }))

    expect(w.text()).toContain('No versions yet.')
    expect(w.text()).toContain('Nothing deployed yet.')
  })
})
