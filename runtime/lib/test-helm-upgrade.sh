  serving=""
  for i in $(seq 1 30); do
    _upg_call GET "/api/knative-regions/${region_id}/component-status" "$admin_token"
    serving=$(echo "$_upg_body" | jq -r '.serving.status // empty' 2>/dev/null || true)
    [ "$serving" = "ready" ] && break
