EOF
  if [ "$_upg_mt" = "1" ]; then
    printf 'edition: multi-tenant\nui:\n  image:\n    multiTenantSuffix: "-mt"\n' > "${_upg_tmp}/install-mt.yaml"
  else
    : > "${_upg_tmp}/install-mt.yaml"
  fi
  helm --kubeconfig "$_upg_kubeconfig" install runr "${_upg_tmp}/from/helm" -n "$_upg_ns" --create-namespace \
    -f "${_upg_tmp}/install.yaml" -f "${_upg_tmp}/install-mt.yaml" --wait --timeout 15m
  _upg_api=$(_upg_gateway_url)
  echo "  console: ${_upg_api}"
  _upg_wait_api || return 1
  local from_version
  from_version=$(echo "$_upg_body" | jq -r .version)
  echo "  /api/version: ${from_version}"

  # ── 2. Data like an existing installation ──
  _upg_log "Data on ${from_tag}"
  if [ "$_upg_mt" = "1" ]; then _upg_mt_data; else _upg_st_data; fi

  _upg_old_ns_before

  # ── 3. helm upgrade, the function under a prober ──
  _upg_log "helm upgrade → this checkout (${mode})"
  _upg_brand_values
  : > "${_upg_tmp}/probe.log"
  if [ -n "$_upg_fn_host" ]; then
    (
      while :; do
        echo "$(date +%s) $(curl -s -o /dev/null -w '%{http_code}' -m 5 -H "Host: ${_upg_fn_host}" "http://${_upg_lb_ip}/")" >> "${_upg_tmp}/probe.log"
        sleep 1
      done
    ) &
    _upg_probe_pid=$!
  fi
  local upgrade_started
  upgrade_started=$(date -u +%FT%TZ)
  local helm_status=0
  [ "$_upg_billing" = "1" ] && _upg_upgrade_set+=(--set billing.enabled=true)
  helm --kubeconfig "$_upg_kubeconfig" upgrade runr "${root}/helm" -n "$_upg_ns" "$mode" \
    -f "${_upg_tmp}/brand.yaml" "${_upg_upgrade_set[@]}" \
    --set "api.image.repository=${to_api%:*}" --set "api.image.tag=${to_api##*:}" \
    --set "ui.image.repository=${to_ui%:*}" --set "ui.image.tag=${to_ui##*:}" \
    --wait --timeout 15m || helm_status=$?
  # the whole log for the checks (a tenancy:migrate line may be further up), its end in the output
  _upg_kubectl -n "$_upg_ns" logs job/runr-bootstrap > "${_upg_tmp}/bootstrap.log" 2>/dev/null || true
  tail -n 60 "${_upg_tmp}/bootstrap.log" | sed 's/^/  bootstrap: /' || true
  if [ "$helm_status" != "0" ]; then
    echo -e "${RED}helm upgrade failed (${helm_status})${NC}"
    _upg_kubectl -n "$_upg_ns" get pods,jobs 2>/dev/null || true
    _upg_kubectl -n "$_upg_ns" logs -l app=runr-migrate --tail=80 2>/dev/null || true
    return 1
  fi
  # the prober keeps going while the checks run
  _upg_wait_api || return 1

  # ── 4. Checks ──
  _upg_log "Checks"
  local to_version
  to_version=$(echo "$_upg_body" | jq -r .version)
  echo "  /api/version: ${from_version} → ${to_version} (the chart's appVersion)"
  _upg_check "/api/version answers" test -n "$to_version"
  local api_images
  api_images=$(_upg_kubectl -n "$_upg_ns" get deploy runr-api runr-horizon runr-scheduler runr-reverb \
    -o jsonpath='{range .items[*]}{.spec.template.spec.containers[0].image}{" "}{end}' | tr ' ' '\n' | sort -u | xargs)
  _upg_check "api, horizon, scheduler and reverb run the new API image" _upg_eq "$api_images" "$to_api"
  _upg_check "the console runs the new UI image" \
    _upg_eq "$(_upg_kubectl -n "$_upg_ns" get deploy runr-ui -o jsonpath='{.spec.template.spec.containers[0].image}')" "${to_ui}${_upg_ui_suffix}"
  _upg_check "pre-upgrade migration job succeeded" \
    test "$(_upg_kubectl -n "$_upg_ns" get jobs -l app=runr-migrate -o json | jq '[.items[] | select(.metadata.name | startswith("runr-migrate-upgrade")) | .status.succeeded // 0] | add')" -ge 1
  _upg_check "no pending migrations" _upg_no_pending_migrations
  _upg_check "the bootstrap Job (post-upgrade hook) succeeded" \
    test "$(_upg_kubectl -n "$_upg_ns" get job runr-bootstrap -o jsonpath='{.status.succeeded}' 2>/dev/null || echo 0)" -ge 1
  # Horizon dashboard through runr-gateway: a single-use link of runr:horizon-link opens it
  local hz_link hz_path
  hz_link=$(_upg_artisan runr:horizon-link 2>/dev/null | head -1 || true)
  hz_path="/${hz_link#*://*/}"
  _upg_call GET "$hz_path"
  _upg_check "Horizon: the link of runr:horizon-link opens the dashboard (${hz_link%%\?*})" \
    bash -c '[[ "$1" == *"/horizon?"* ]] && [ "$2" = 200 ]' _ "$hz_link" "$_upg_code"
  _upg_call GET "$hz_path"
  _upg_check "Horizon: the link works once (second use 403)" _upg_eq "$_upg_code" 403

  if [ "$_upg_mt" = "1" ]; then _upg_mt_checks; else _upg_st_checks; fi

  # The installed version's image namespace: nothing left in the workloads (control plane: the chart's
  # runr.image helper over the reused values; region: region:reconcile image-registry), the
  # running pods (old Knative revisions scale down) and the database (migrations)
  _upg_log "Image namespace ${_UPG_OLD_NS} → ${_UPG_NEW_NS}"
  local left_workloads left_pods left_rows kept
  left_workloads=$(_upg_old_workloads)
  _upg_check "no workload references ${_UPG_OLD_NS}/ (Deployments, StatefulSets, DaemonSets, CronJobs, Knative Services)" test -z "$left_workloads"
  [ -z "$left_workloads" ] || echo "$left_workloads" | sed 's/^/    /'
  kept=$(KEPT=1 _upg_old_pods || true)
  [ -z "$kept" ] || { echo "  pods region:reconcile keeps running (in-memory queue Redis, sandbox node installers; their templates moved):"; echo "$kept" | sed 's/^/    /'; }
  for i in $(seq 1 60); do
    left_pods=$(_upg_old_pods)
    [ -z "$left_pods" ] && break
    sleep 10
  done
  _upg_check "no running pod runs an image of ${_UPG_OLD_NS}/" test -z "$left_pods"
  [ -z "$left_pods" ] || echo "$left_pods" | sed 's/^/    /'
  left_rows=$(_upg_old_rows)
  _upg_check "no database row (central and tenant schemas) references ${_UPG_OLD_NS}/" test -z "$left_rows"
  [ -z "$left_rows" ] || echo "$left_rows" | sed 's/^/    /'
  _upg_check "the region agent runs ghcr.io/brf-tech/runr/agent" \
    bash -c '[ "$1" = 1 ] || [[ "$2" == ghcr.io/brf-tech/runr/agent:* ]]' _ "$_upg_mt" \
    "$(_upg_kubectl -n observability get deploy runr-agent -o jsonpath='{.spec.template.spec.containers[0].image}' 2>/dev/null)"

  # White-label
  _upg_call GET /api/branding
  echo "  /api/branding: $(echo "$_upg_body" | jq -c '{product_name, company_name, login_headline, primary_scale, is_default_brand}' 2>/dev/null)"
  _upg_check "/api/branding: product name" _upg_eq "$(echo "$_upg_body" | jq -r .product_name)" "Acme Cloud"
  _upg_check "/api/branding: company name" _upg_eq "$(echo "$_upg_body" | jq -r .company_name)" "Acme Example Ltd"
  _upg_check "/api/branding: not the default brand" _upg_eq "$(echo "$_upg_body" | jq -r .is_default_brand)" false
  _upg_check "/api/branding: primary 300–900 scale as given" \
    _upg_eq "$(echo "$_upg_body" | jq -r '[.palette["300"], .palette["900"]] | join("|")' 2>/dev/null)" "125 170 230|7 31 77"
  _upg_check "/api/branding: logo URLs set" test "$(echo "$_upg_body" | jq -r '[.logo_light_url, .logo_dark_url, .logo_mark_url] | map(select(. != null and . != "")) | length')" = 3
  local asset_type
  asset_type=$(curl -s -o "${_upg_tmp}/logo" -w '%{content_type}' -H "Host: ${_upg_host}" "${_upg_api}/api/branding/assets/logo_light")
  _upg_check "brand logo served from its data: URI (image/svg+xml)" _upg_prefix "$asset_type" image/svg+xml
  _upg_check "brand logo is the given SVG" _upg_contains "$(cat "${_upg_tmp}/logo")" "Acme Cloud"
  _upg_check "console UI answers" _upg_contains "$(curl -s -H "Host: ${_upg_host}" "${_upg_api}/")" '<div id="app"'

  echo ""
  if [ "$_upg_failures" = "0" ]; then
    echo -e "${GREEN}${BOLD}Upgrade e2e: ${_upg_checks} checks passed${NC}"
    return 0
  fi
  echo -e "${RED}${BOLD}Upgrade e2e: ${_upg_failures} of ${_upg_checks} checks failed${NC}"
  return 1
}
