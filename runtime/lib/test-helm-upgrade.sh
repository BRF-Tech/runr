_upg_cleanup_all() {
  kind_cleanup_begin "$_upg_cluster"
  echo "Cleanup..."
  [ -n "$_upg_probe_pid" ] && kill "$_upg_probe_pid" 2>/dev/null || true
  # stops it unless another run's Kind cluster still uses it
  [ -n "$_upg_cpk" ] && stop_cloud_provider_kind "$_upg_cluster" || true
  if [ "$_upg_cleanup" = "1" ] && [ -n "$_upg_cluster" ]; then
    [ -n "$_upg_tmp" ] && rm -rf "$_upg_tmp"
  elif [ -n "$_upg_cluster" ]; then
    echo "Kept: kind cluster ${_upg_cluster}, kubeconfig ${_upg_kubeconfig}"
  fi
  # Deletes the cluster (or keeps it, --no-cleanup) and releases the Kind lock once it is gone
  finish_kind_cluster "$_upg_cluster" "$_upg_cleanup" || true
}

# _upg_from_repo ROOT REF api|ui — image repository of the API / UI in REF's chart values
_upg_from_repo() {
  git -C "$1" show "$2:helm/values.yaml" | sed -n "s#^ *repository: *\"\{0,1\}\([^\" ]*/runr/$3\)\"\{0,1\} *\$#\1#p" | head -1
}

# Images of the installed version: pulled when public, otherwise built from the git ref
_upg_from_images() {
  local ref="$1" tag="$2" root="$3"
  local api="${_upg_from_api_repo}:${tag}" ui="${_upg_from_ui_repo}:${tag}${_upg_ui_suffix}"
  if docker image inspect "$api" >/dev/null 2>&1 && docker image inspect "$ui" >/dev/null 2>&1; then
    echo "  ${api}, ${ui}: present"
    return
  fi
  if docker pull -q "$api" >/dev/null 2>&1 && docker pull -q "$ui" >/dev/null 2>&1; then
    echo "  ${api}, ${ui}: pulled"
    return
  fi
  echo "  ${api} / ${ui} not public: building them from ${ref}"
  local src="${_upg_tmp}/from-src"
  mkdir -p "$src"
  git -C "$root" archive --format=tar "$ref" api vue docs | tar -x -C "$src"
  mkdir -p "${src}/api/resources/docs" && cp "${src}"/docs/*.md "${src}/api/resources/docs/"
  docker build -q --pull -f "${src}/api/Dockerfile.prod" --build-arg "APP_VERSION=v${tag}" -t "$api" "${src}/api" >/dev/null
  _upg_build_ui "$ui" "${src}/vue"
}

# UI image as runtime/lib/deploy-images.sh builds it; the multi-tenant edition has the Tenancy and
# Auth Provider modules built in (chart: ui.image.multiTenantSuffix)
_upg_build_ui() {
  local image="$1" context="$2" modules=false
  [ "$_upg_mt" = "1" ] && modules=true
  docker build -q --pull --build-arg VITE_WS_PROXY=true --build-arg VITE_REVERB_KEY=runr-key \
    --build-arg "VITE_TENANCY_ENABLED=${modules}" --build-arg "VITE_AUTH_PROVIDER_ENABLED=${modules}" \
    --build-arg VITE_TICKET_ENABLED=true --build-arg VITE_BILLING_ENABLED=true -t "$image" "$context" >/dev/null
}

# Images of this checkout (what the upgrade installs)
_upg_to_images() {
  local root="$1" api="$2" ui="$3"
  mkdir -p "${root}/api/resources/docs" && cp "${root}"/docs/*.md "${root}/api/resources/docs/"
  docker build -q --pull -f "${root}/api/Dockerfile.prod" --build-arg "APP_VERSION=$(resolve_app_version "$root")" -t "$api" "${root}/api" >/dev/null
  _upg_build_ui "${ui}${_upg_ui_suffix}" "${root}/vue"
  echo "  ${api}, ${ui}${_upg_ui_suffix}: built from this checkout"
}

