# _upg_call METHOD PATH [TOKEN] [JSON] → $_upg_code, $_upg_body
_upg_call() {
  local method="$1" path="$2" token="${3:-}" body="${4:-}"
  local args=(-s -o "${_upg_tmp}/body" -w '%{http_code}' -X "$method" -H "Host: ${_upg_host}" -H 'Accept: application/json' -m 60)
  [ -n "$token" ] && args+=(-H "Authorization: Bearer ${token}")
  [ -n "$_upg_tenant" ] && args+=(-H "X-Tenant-ID: ${_upg_tenant}")
  [ -n "$body" ] && args+=(-H 'Content-Type: application/json' --data-binary "$body")
  _upg_code=$(curl "${args[@]}" "${_upg_api}${path}" || echo 000)
  _upg_body=$(cat "${_upg_tmp}/body" 2>/dev/null || true)
}

# _upg_call_ok … — like _upg_call, exits when the status is not 2xx
_upg_call_ok() {
  _upg_call "$@"
  if [[ ! "$_upg_code" =~ ^2 ]]; then
    echo -e "${RED}$1 $2 → ${_upg_code}: ${_upg_body:0:600}${NC}"
    exit 1
  fi
}

