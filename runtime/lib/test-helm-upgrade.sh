# Records one check: _upg_check "description" <command...>
_upg_check() {
  local desc="$1"; shift
  _upg_checks=$((_upg_checks + 1))
  if "$@" >/dev/null 2>&1; then
    echo -e "  ${GREEN}✓${NC} ${desc}"
  else
    echo -e "  ${RED}✗ ${desc}${NC}"
    _upg_failures=$((_upg_failures + 1))
  fi
}

