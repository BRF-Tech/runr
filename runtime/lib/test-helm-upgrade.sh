# Images the nodes would otherwise pull (an image kind cannot load is pulled by the nodes)
_upg_load_images() {
  local img
  for img in "$@"; do
    docker image inspect "$img" >/dev/null 2>&1 || pull_image "$img" || true
    if kind load docker-image "$img" --name "$_upg_cluster" >/dev/null 2>&1; then
      echo "  ${img}: loaded"
    else
      echo "  ${img}: not loaded (the nodes pull it)"
    fi
  done
}

