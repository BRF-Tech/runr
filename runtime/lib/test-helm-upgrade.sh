# GET the function through the region's Traefik (cloud-provider-kind address, Host header). Never
# fails: the callers retry, and under `set -e` a failed `out=$(…)` (curl 7 while the route is not
# up yet) would end the whole run without a word. A curl error is returned as the output instead.
_upg_function_get() {
  local rc=0
  curl -sS -m 10 -H "Host: ${_upg_fn_host}" "http://${_upg_lb_ip}/" 2>&1 || rc=$?
  [ "$rc" = 0 ] || echo " (curl exit ${rc})"
}

_upg_wait_deployment_active() {
  local project="$1" token="$2" i status=""
  for i in $(seq 1 60); do
    _upg_call GET "/api/projects/${project}" "$token"
    status=$(echo "$_upg_body" | jq -r '.data.latest_deployment.status // empty' 2>/dev/null || true)
    [ "$status" = "active" ] && return 0
    [ "$status" = "failed" ] && break
    sleep 5
  done
  echo -e "${RED}deployment of ${project}: ${status:-no status}${NC}"
  return 1
}

# _upg_old_workloads — "<kind> <ns>/<name>: <image>" for every workload of the cluster (Deployment,
# StatefulSet, DaemonSet, CronJob, Knative Service; no controller-owned ones such as a Knative
# revision's Deployment) whose pod template has an image or env value of the installed version's
# namespace (outside ghcr.io/brf-tech/runr)
_upg_old_workloads() {
  local json
  json=$( { _upg_kubectl get deployments,statefulsets,daemonsets,cronjobs -A -o json 2>/dev/null | jq -c '.items[]'
            _upg_kubectl get ksvc -A -o json 2>/dev/null | jq -c '.items[]'; } | jq -s '{items: .}')
  echo "$json" | jq -r --arg ns "${_UPG_OLD_NS}/" --arg new "${_UPG_NEW_NS}/" '
    .items[]
    | select([.metadata.ownerReferences[]? | select(.controller == true)] | length == 0)
    | . as $o
    | (if .kind == "CronJob" then .spec.jobTemplate.spec.template.spec else .spec.template.spec end) as $p
    | ([$p.initContainers[]?, $p.containers[]?] | map(.image, (.env[]?.value // empty)) | map(select(type == "string" and startswith($ns) and (startswith($new) | not))) | unique)[]
    | "\($o.kind) \($o.metadata.namespace)/\($o.metadata.name): \(.)"'
}

# _upg_old_pods — "<ns>/<pod>: <image>" for every pod that is not finished and runs an image of
# the installed version's namespace, apart from the pods region:reconcile keeps running on purpose
# (the region's queue Redis, the node installers of the sandbox runtimes; their templates move).
# KEPT=1: those pods only
_upg_old_pods() {
  _upg_kubectl get pods -A -o json 2>/dev/null | jq -r --arg ns "${_UPG_OLD_NS}/" --arg new "${_UPG_NEW_NS}/" --arg kept "${KEPT:-0}" '
    .items[]
    | select(.status.phase != "Succeeded" and .status.phase != "Failed")
    | select((.metadata.labels["app.kubernetes.io/name"] == "runr-redis" or .metadata.namespace == "runr-sandbox") == ($kept == "1"))
    | . as $o
    | ([.spec.initContainers[]?, .spec.containers[]?] | map(.image) | map(select(startswith($ns) and (startswith($new) | not))) | unique)[]
    | "\($o.metadata.namespace)/\($o.metadata.name): \(.)"'
}

# _upg_old_rows — rows of the central and every tenant schema whose image columns
# (App\Support\Images\RegistryMoveColumns, runtimes) name the installed version's namespace
# (outside ghcr.io/brf-tech/runr), as "<schema>.<table>.<column> <count>" lines (nothing when there
# are none)
_upg_old_rows() {
  _upg_psql "select c.table_schema || '.' || c.table_name || '.' || c.column_name || ' ' || n.count
    from information_schema.columns c,
      lateral (select (xpath('/row/n/text()', query_to_xml(format('select count(*) as n from %I.%I where strpos(replace(replace(cast(%I as text), %L, %L), %L, %L), %L) > 0',
        c.table_schema, c.table_name, c.column_name, '\/', '/', '${_UPG_NEW_NS}/', '', '${_UPG_OLD_NS}/'), false, true, '')))[1]::text::int as count) n
    where (c.table_schema = 'public' or c.table_schema like 'tenant%')
      and (c.table_name, c.column_name) in (('executor_images','docker_image'), ('runtimes','manifest'), ('runtimes','manifest_source'),
        ('runtimes','files'), ('sandboxes','image'), ('region_supply_chain_settings','admission_exempt_images'),
        ('region_supply_chain_settings','caas_allowed_registries'), ('container_configs','image'), ('deployments','deploy_config'),
        ('knative_regions','knative_settings'), ('knative_regions','gpu_settings'), ('knative_regions','model_storage'),
        ('ai_model_services','image'), ('bindings','settings'), ('binding_region_services','config'),
        ('image_security_reports','image_ref'))
      and n.count > 0
    order by 1"
}

# Before the upgrade: what of its image namespace the installed version holds (the checks
# after it then prove the move, not an empty start)
_upg_old_ns_before() {
  local workloads rows
  workloads=$(_upg_old_workloads)
  rows=$(_upg_old_rows)
  echo "  ${_UPG_OLD_NS}/ before the upgrade: $(printf '%s' "$workloads" | grep -c . || true) workload image(s), database: $(echo "$rows" | awk 'NF {n += $2} END {print n + 0}') row(s)"
  printf '%s\n' "$workloads" "$rows" | grep . | sed 's/^/    /' || true
}

# Single-tenant data: users, the cluster as a region, the function, API tokens. The variables
# are cmd_test_helm_upgrade's locals (bash scoping: callees share them).
_upg_st_data() {
  admin_token=$(_upg_login admin "$admin_pw")
  [ -n "$admin_token" ] || { echo -e "${RED}admin login failed: ${_upg_body}${NC}"; return 1; }
  _upg_call_ok PATCH /api/settings "$admin_token" '{"base_domain":"upgrade.test"}'
  _upg_call_ok POST /api/users "$admin_token" \
    "$(jq -nc --arg p "$dev_pw" '{name: "Dev User", username: "dev", email: "dev@example.test", password: $p}')"
  dev_token=$(_upg_login dev "$dev_pw")
  [ -n "$dev_token" ] || { echo -e "${RED}dev login failed: ${_upg_body}${NC}"; return 1; }
  echo "  users: admin, dev"
  # A release with roles (0.5.0 and later) gave dev its default role already: the upgrade keeps it
  _upg_call GET /api/members "$admin_token"
  dev_role_before=""
  [ "$_upg_code" = "200" ] && dev_role_before=$(echo "$_upg_body" | jq -r '[.members[]? | select(.username == "dev")][0].role // empty' 2>/dev/null || true)

  # The same cluster as a region: the API reaches it through its in-cluster address
  region_id=""
  region_kc=$(sed -E 's#server: https://.*#server: https://kubernetes.default.svc#' "$_upg_kubeconfig")
  _upg_call_ok POST /api/registry-setup/start "$admin_token" "$(jq -nc --arg kc "$region_kc" --arg n "$_upg_region" \
    '{name: $n, kubeconfig: $kc, nodes: [], registry_mode: "internal", storage_type: "pvc", pvc_config: {storageClass: "standard", size: "1Gi"}}')"
  setup_token=$(echo "$_upg_body" | jq -r .setup_token)
  for i in $(seq 1 60); do
    _upg_call GET "/api/registry-setup/${setup_token}/status" "$admin_token"
    status=$(echo "$_upg_body" | jq -r '.status // empty' 2>/dev/null || true)
    [ "$status" = "ready" ] && { region_id=$(echo "$_upg_body" | jq -r .region_id); break; }
    [ "$status" = "error" ] && { echo -e "${RED}region setup: ${_upg_body}${NC}"; return 1; }
    sleep 10
  done
  [ -n "$region_id" ] || { echo -e "${RED}region setup did not finish: ${_upg_body}${NC}"; return 1; }
  echo "  region ${_upg_region}: ${region_id}"

  # 0.4.x renders an empty ingress_trusted_ips as {} into the Traefik chart values, which the chart's
  # schema refuses (fixed in this release): the old region gets an entry so Serving installs there
  _upg_call_ok PUT "/api/knative-regions/${region_id}/settings" "$admin_token" '{"ingress_trusted_ips":["127.0.0.1/32"]}'
  for component in operator serving; do
    for i in $(seq 1 30); do
      _upg_call POST "/api/knative-regions/${region_id}/install-${component}" "$admin_token" '{}'
      [[ "$_upg_code" =~ ^2 ]] && break
      sleep 10
    done
    for i in $(seq 1 90); do
      _upg_call GET "/api/knative-regions/${region_id}/component-status" "$admin_token"
      status=$(echo "$_upg_body" | jq -r ".${component}.status // empty" 2>/dev/null || true)
      [ "$status" = "ready" ] && break
      [ "$status" = "error" ] && { echo -e "${RED}${component}: ${_upg_body}${NC}"; return 1; }
      sleep 10
    done
    [ "$status" = "ready" ] || { echo -e "${RED}${component} not ready: ${_upg_body}${NC}"; return 1; }
    echo "  knative ${component}: ready"
  done
  _upg_kubectl -n observability rollout status deploy/runr-agent --timeout=300s

  # The function: Python over HTTP with a plain and a (0.4.x: plain) secret-like var
  _upg_call_ok GET /api/settings "$admin_token"
  py_version=$(echo "$_upg_body" | jq -r '[.executor_images[] | select(.runtime == "python" and .is_default)][0].version')
  _upg_call_ok POST /api/projects "$admin_token" "$(jq -nc --arg r "$region_id" --arg v "$py_version" \
    '{name: "upgrade-fn", knative_region_id: $r, service_type: "xaas", runtime: "python", runtime_version: $v,
      config: {trigger_type: "http", cpu: "250m", memory_mb: 128, env_vars: {PLAIN_VAR: "hello-plain", API_TOKEN: "s3cr3t-044"}}}')"
  project=$(echo "$_upg_body" | jq -r '.id // .data.id')
  slug=$(echo "$_upg_body" | jq -r '.slug // .data.slug')
  _upg_call_ok POST "/api/projects/${project}/code" "$admin_token" \
    "$(jq -nc --arg c "$(_upg_function_code)" '{code: $c, message: "upgrade e2e"}')"
  version=$(echo "$_upg_body" | jq -r '.version.id')
  _upg_call_ok POST "/api/projects/${project}/deploy" "$admin_token" "$(jq -nc --arg v "$version" '{version_id: $v}')"
  _upg_wait_deployment_active "$project" "$admin_token" || return 1

  _upg_lb_ip=$(_upg_kubectl -n knative-serving get svc traefik -o jsonpath='{.status.loadBalancer.ingress[0].ip}')
  _upg_fn_host=$(_upg_kubectl -n "$_upg_region" get ksvc "$slug" -o jsonpath='{.status.url}' | sed -E 's#^https?://##')
  out=""
  for i in $(seq 1 30); do
    out=$(_upg_function_get)
    [ "$(echo "$out" | jq -r '.plain // empty' 2>/dev/null)" = "hello-plain" ] && break
    sleep 5
  done
  echo "  function ${_upg_fn_host} (via ${_upg_lb_ip}): ${out}"
  [ "$(echo "$out" | jq -r '.plain // empty' 2>/dev/null)" = "hello-plain" ] || { echo -e "${RED}function does not answer after 30 tries (last: ${out:-no response})${NC}"; return 1; }

  # A CaaS project of an image of RunR's mirror (stored only: its image reference moves with the upgrade)
  _upg_call_ok POST /api/projects "$admin_token" "$(jq -nc --arg r "$region_id" --arg i "${_UPG_OLD_NS}/reqs/nginx:1.27-alpine" \
    '{name: "upgrade-caas", knative_region_id: $r, service_type: "caas", config: {image: $i, trigger_type: "http", cpu: "250m", memory_mb: 128}}')"
  caas_project=$(echo "$_upg_body" | jq -r '.id // .data.id')
  echo "  CaaS project ${caas_project}: ${_UPG_OLD_NS}/reqs/nginx:1.27-alpine (not deployed)"

  _upg_call_ok POST /api/tokens "$admin_token" '{"name":"ci-full","abilities":["*"]}'
  full_token=$(echo "$_upg_body" | jq -r .plain_token)
  _upg_call_ok POST /api/tokens "$admin_token" '{"name":"ci-read","abilities":["projects:read"]}'
  read_token=$(echo "$_upg_body" | jq -r .plain_token)
  echo "  API tokens: ci-full (*), ci-read (projects:read)"
  echo "  env_vars in the database before: $(_upg_psql "select env_vars from xaas_configs where project_id = '${project}'")"
  if [ "$_upg_dedicated" = "1" ]; then _upg_dedicate_registry_node || return 1; fi
}

# --dedicated-worker, on the installed version: the worker the registry's (node-bound) volume is on
# becomes the region's dedicated project worker, after the registry was installed
_upg_dedicate_registry_node() {
  _upg_zot_node=$(_upg_kubectl -n runr-registry get pod -l app.kubernetes.io/instance=runr-zot -o jsonpath='{.items[0].spec.nodeName}' 2>/dev/null)
  [ -n "$_upg_zot_node" ] || { echo -e "${RED}--dedicated-worker: the registry runs on no node${NC}"; return 1; }
  if _upg_kubectl get node "$_upg_zot_node" -o jsonpath='{.metadata.labels}' | grep -q 'node-role.kubernetes.io/control-plane'; then
    echo -e "${RED}--dedicated-worker: the registry's volume is on the control-plane ${_upg_zot_node}, which is no worker to select${NC}"
    return 1
  fi
  _upg_call_ok POST "/api/knative-regions/${region_id}/workers" "$admin_token" "$(jq -nc --arg n "$_upg_zot_node" '{nodes: [$n]}')"
  echo "  ${_upg_zot_node} (the registry's volume) selected as the dedicated worker; Zot's tolerations on ${from_tag}:" \
    "$(_upg_kubectl -n runr-registry get statefulset runr-zot -o jsonpath='{.spec.template.spec.tolerations}' 2>/dev/null || true)"
  # From 0.5.4 on the worker selection gives Zot the toleration itself: reconcile then has nothing to add
  _upg_zot_tolerated_before=0
  if _upg_zot_tolerates; then _upg_zot_tolerated_before=1; fi
}

# Zot's StatefulSet tolerates the dedicated-worker taint
_upg_zot_tolerates() {
  _upg_kubectl -n runr-registry get statefulset runr-zot -o json \
    | jq -e '[.spec.template.spec.tolerations[]? | select(.key == "runr.dev/dedicated" and .value == "projects" and (.effect // "NoSchedule") == "NoSchedule")] | length > 0' >/dev/null
}

# Zot rolled out and runs on the node of its volume
_upg_zot_runs_on_its_node() {
  _upg_kubectl -n runr-registry rollout status statefulset/runr-zot --timeout=300s >/dev/null 2>&1 \
    && [ "$(_upg_kubectl -n runr-registry get pod runr-zot-0 -o jsonpath='{.status.phase} {.spec.nodeName}')" = "Running ${_upg_zot_node}" ]
}

# pods (any namespace) waiting Pending on the dedicated-worker taint
_upg_pending_on_taint() {
  _upg_kubectl get pods -A -o json 2>/dev/null | jq -r '.items[]
    | select(.status.phase == "Pending")
    | select([.status.conditions[]? | select(.type == "PodScheduled" and .status == "False" and ((.message // "") | contains("runr.dev/dedicated")))] | length > 0)
    | "\(.metadata.namespace)/\(.metadata.name)"'
}

# --dedicated-worker checks after the upgrade
_upg_dedicated_checks() {
  local pending
  if [ "$_upg_zot_tolerated_before" = "1" ]; then
    _upg_check "region:reconcile (bootstrap) leaves the toleration Zot had on ${from_tag} alone (up to date)" \
      grep -qF "[dedicated-worker-toleration] up to date" "${_upg_tmp}/bootstrap.log"
  else
    _upg_check "region:reconcile (bootstrap) gave Zot the toleration of runr.dev/dedicated=projects:NoSchedule" \
      grep -qF "[dedicated-worker-toleration] added the toleration of runr.dev/dedicated=projects:NoSchedule to StatefulSet runr-registry/runr-zot" "${_upg_tmp}/bootstrap.log"
  fi
  _upg_check "Zot's StatefulSet tolerates the dedicated-worker taint" _upg_zot_tolerates
  _upg_check "Zot runs on its dedicated worker ${_upg_zot_node}" _upg_zot_runs_on_its_node
  _upg_kubectl -n runr-registry rollout restart statefulset/runr-zot >/dev/null
  _upg_check "Zot restarted runs on ${_upg_zot_node} again" _upg_zot_runs_on_its_node
  for i in $(seq 1 12); do
    pending=$(_upg_pending_on_taint)
    [ -z "$pending" ] && break
    sleep 10
  done
  _upg_check "no pod waits Pending on the dedicated-worker taint" test -z "$pending"
  [ -z "$pending" ] || echo "$pending" | sed 's/^/    /'
}

