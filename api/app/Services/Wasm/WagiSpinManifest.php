<?php

namespace App\Services\Wasm;

use App\Services\Runtimes\Placeholders;

/**
 * spin.toml of a WebAssembly function on Spin's WAGI executor (runtimes with a `wagi` section:
 * the built-in wasm-exec, platform runtimes such as Q on Wasm — docs/wasm.md#wasm-exec).
 *
 * WAGI is the CGI contract of Spin's HTTP trigger (spin-trigger-http `executor = { type = "wagi" }`,
 * part of the Spin runtime the pinned containerd-shim-spin embeds): the request body on stdin, the
 * request in CGI environment variables (REQUEST_METHOD, PATH_INFO, QUERY_STRING, CONTENT_TYPE,
 * HTTP_<HEADER> …), argv from `argv`, and the response on stdout — CGI headers (Content-Type or
 * Location, optional Status), a blank line, the body. Any WASI preview 1 command module works — the
 * shim adapts it to a component with the WASI command adapter — and so does a WASI 0.2 command
 * component (what wasm-exec builds Go into).
 *
 * The component's source is main.wasm, what the build produces (compiled from the project, or an
 * uploaded module); with `files` the project's files are mapped read-only into the component under
 * their own names (an interpreter reads its script from there); `environment` plus RUNR_RUNTIME,
 * RUNR_RUNTIME_VERSION, RUNR_HANDLER and RUNR_FILENAME are the component's static environment.
 */
final class WagiSpinManifest
{
    public const MODULE = 'main.wasm';

    /** Project files RunR reads itself and never maps into the component. */
    public const RUNR_FILES = ['spin.toml', 'wasm.upload'];

    /**
     * @param  array{argv: string, files: bool, environment: array<string, string>}  $wagi
     * @param  list<string>  $projectFiles  the project's file names
     * @param  array<string, string>  $values  placeholder values (version, file, handler, …)
     * @param  array<string, string>  $environment  RUNR_* contract values
     */
    public static function render(string $appName, array $wagi, array $projectFiles, array $values, array $environment): string
    {
        $argv = Placeholders::render($wagi['argv'] ?? '${SCRIPT_NAME} ${ARGS}', $values);
        $env = $environment + array_map(fn ($v) => Placeholders::render((string) $v, $values), $wagi['environment'] ?? []);
        $files = ($wagi['files'] ?? false)
            ? array_values(array_filter($projectFiles, fn ($f) => ! in_array($f, self::RUNR_FILES, true) && $f !== self::MODULE))
            : [];
        sort($files);
        ksort($env);

        $lines = [
            '# Generated by RunR for a WAGI function (docs/wasm.md#wasm-exec). A project can bring its own spin.toml.',
            'spin_manifest_version = 2',
            '',
            '[application]',
            'name = '.self::str(self::appName($appName)),
            'version = "0.1.0"',
            '',
            '[[trigger.http]]',
            'route = "/..."',
            'component = "function"',
            'executor = { type = "wagi", argv = '.self::str($argv).' }',
            '',
            '[component.function]',
            'source = '.self::str(self::MODULE),
            'files = '.self::list($files),
        ];
        if ($env !== []) {
            $pairs = [];
            foreach ($env as $k => $v) {
                $pairs[] = self::key((string) $k).' = '.self::str((string) $v);
            }
            $lines[] = 'environment = { '.implode(', ', $pairs).' }';
        }

        return implode("\n", $lines)."\n";
    }

    /** A TOML basic string. */
    public static function str(string $value): string
    {
        $escaped = '';
        foreach (mb_str_split($value) as $ch) {
            $escaped .= match (true) {
                $ch === '"' => '\\"',
                $ch === '\\' => '\\\\',
                $ch === "\n" => '\\n',
                $ch === "\r" => '\\r',
                $ch === "\t" => '\\t',
                mb_ord($ch) < 0x20 || mb_ord($ch) === 0x7F => sprintf('\\u%04X', mb_ord($ch)),
                default => $ch,
            };
        }

        return '"'.$escaped.'"';
    }

    /** @param list<string> $items */
    private static function list(array $items): string
    {
        return '['.implode(', ', array_map([self::class, 'str'], $items)).']';
    }

    private static function key(string $key): string
    {
        return preg_match('/^[A-Za-z0-9_-]+$/', $key) ? $key : self::str($key);
    }

    /** Spin application names: lowercase letters, digits and dashes. */
    private static function appName(string $name): string
    {
        $name = trim((string) preg_replace('/[^a-z0-9-]+/', '-', strtolower($name)), '-');

        return $name !== '' ? $name : 'runr-function';
    }
}
