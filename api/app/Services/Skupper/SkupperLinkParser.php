<?php

namespace App\Services\Skupper;

use Symfony\Component\Yaml\Yaml;

/**
 * Reads the link material a Managed PostgreSQL user pastes (YAML or JSON, several documents
 * separated by "---" or a v1 List). Accepted, Skupper v2 (skupper.io/v2*):
 *
 *  - AccessToken  {spec: {url, code, ca}} — redeemed by the Skupper controller into a Link;
 *  - Link + Secret (output of `skupper link generate`) — used as is.
 *
 * Only spec / data are kept: names, namespaces and labels are RunR's.
 */
class SkupperLinkParser
{
    /**
     * @return array{kind:'AccessToken', spec:array}|array{kind:'Link', spec:array, secret:array{type:string,data:array}}
     *
     * @throws \InvalidArgumentException with a user-facing message
     */
    public function parse(string $text): array
    {
        $docs = $this->documents($text);

        $token = $this->first($docs, 'AccessToken');
        $link = $this->first($docs, 'Link');
        $secret = $this->first($docs, 'Secret');

        if ($token) {
            return ['kind' => 'AccessToken', 'spec' => $this->accessTokenSpec($token)];
        }

        if ($link) {
            return $this->linkWithSecret($link, $docs);
        }

        if ($secret && isset($secret['metadata']['labels']['skupper.io/type'])) {
            throw new \InvalidArgumentException('This is a Skupper v1 token (Secret with skupper.io/type). RunR links through Skupper v2: paste an AccessToken or a Link generated by Skupper v2.');
        }

        throw new \InvalidArgumentException('No Skupper v2 AccessToken or Link found. Paste the YAML you received for the Managed PostgreSQL database.');
    }

    /**
     * @return list<array>
     */
    private function documents(string $text): array
    {
        $text = trim(str_replace("\r\n", "\n", $text));
        if ($text === '') {
            throw new \InvalidArgumentException('The link token is empty.');
        }

        $docs = [];
        foreach (preg_split('/^---[ \t]*$/m', $text) as $part) {
            if (trim($part) === '') {
                continue;
            }
            try {
                $doc = Yaml::parse($part);
            } catch (\Throwable $e) {
                throw new \InvalidArgumentException('The link token is not valid YAML/JSON: '.$e->getMessage());
            }
            if (! is_array($doc)) {
                continue;
            }
            if (($doc['kind'] ?? null) === 'List' && is_array($doc['items'] ?? null)) {
                array_push($docs, ...array_filter($doc['items'], 'is_array'));
            } else {
                $docs[] = $doc;
            }
        }

        return $docs;
    }

    private function first(array $docs, string $kind): ?array
    {
        foreach ($docs as $doc) {
            if (($doc['kind'] ?? null) !== $kind) {
                continue;
            }
            if ($kind !== 'Secret' && ! str_starts_with((string) ($doc['apiVersion'] ?? ''), 'skupper.io/v2')) {
                throw new \InvalidArgumentException("{$kind} must be skupper.io/v2 (found ".($doc['apiVersion'] ?? 'no apiVersion').').');
            }

            return $doc;
        }

        return null;
    }

    private function accessTokenSpec(array $token): array
    {
        $spec = (array) ($token['spec'] ?? []);
        $url = trim((string) ($spec['url'] ?? ''));
        $code = trim((string) ($spec['code'] ?? ''));
        $ca = trim((string) ($spec['ca'] ?? ''));

        if (! preg_match('#^https://\S+$#', $url)) {
            throw new \InvalidArgumentException('AccessToken spec.url must be an https URL.');
        }
        if ($code === '') {
            throw new \InvalidArgumentException('AccessToken spec.code is empty.');
        }
        if (! str_contains($ca, 'BEGIN CERTIFICATE')) {
            throw new \InvalidArgumentException('AccessToken spec.ca must be a PEM certificate.');
        }

        $out = ['url' => $url, 'code' => $code, 'ca' => $ca."\n"];
        if (isset($spec['linkCost']) && is_numeric($spec['linkCost'])) {
            $out['linkCost'] = (int) $spec['linkCost'];
        }

        return $out;
    }

    private function linkWithSecret(array $link, array $docs): array
    {
        $spec = (array) ($link['spec'] ?? []);
        if (empty($spec['endpoints']) || ! is_array($spec['endpoints'])) {
            throw new \InvalidArgumentException('Link spec.endpoints is empty.');
        }

        // The Link's TLS Secret: the one it names, else the only Secret given
        $wanted = $spec['tlsCredentials'] ?? null;
        $secrets = array_values(array_filter($docs, fn ($d) => ($d['kind'] ?? null) === 'Secret'));
        $secret = null;
        foreach ($secrets as $candidate) {
            if ($wanted === null || ($candidate['metadata']['name'] ?? null) === $wanted) {
                $secret = $candidate;
                break;
            }
        }
        $secret ??= count($secrets) === 1 ? $secrets[0] : null;

        if (! $secret) {
            throw new \InvalidArgumentException('The Link needs its TLS Secret (paste both documents from `skupper link generate`).');
        }

        $data = (array) ($secret['data'] ?? []);
        foreach ((array) ($secret['stringData'] ?? []) as $k => $v) {
            $data[$k] = base64_encode((string) $v);
        }
        if (! isset($data['ca.crt'])) {
            throw new \InvalidArgumentException('The Link Secret has no ca.crt.');
        }

        unset($spec['tlsCredentials']);

        return [
            'kind' => 'Link',
            'spec' => $spec,
            'secret' => ['type' => (string) ($secret['type'] ?? 'kubernetes.io/tls'), 'data' => $data],
        ];
    }
}
