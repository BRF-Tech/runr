<?php

namespace App\Triggers;

use App\Models\ProjectTrigger;
use App\Rules\CronSchedule;
use Illuminate\Validation\Rules\In;
use Illuminate\Validation\ValidationRuleParser;

/**
 * The schema of one runr.yaml `triggers:` entry (docs/triggers.md#runryaml), derived from the
 * validation rules of the registered trigger types (TriggerType::rules()) — the one description
 * of the trigger config that the server validates with and the CLI checks runr.yaml against
 * before it sends anything (cli/internal/projectfile embeds a copy of
 * resources/triggers/triggers.schema.json, `php artisan triggers:schema` writes it).
 *
 * The document: `entry` (the fields every entry has: type, name, enabled) and `types` (per type
 * the JSON Schema of its config keys, which sit at the top level of a runr.yaml entry). The
 * keywords are a subset of JSON Schema 2020-12 with Laravel's meaning where the two differ:
 *
 *  - type: string, integer (a string of digits too), number (a numeric string too), boolean
 *    (also 0, 1, "0", "1"), array (Laravel's array rule: a list or a mapping), null (nullable);
 *  - required: present and not empty (not null, "", [] or {});
 *  - items: every element of a list, every value of a mapping;
 *  - enum: compared as PHP strings ("1" matches 1 and true);
 *  - pattern / not.pattern: RE2 syntax; format: cron (App\Rules\CronSchedule) or timezone (an
 *    IANA zone, backward-compatible names included).
 *
 * What a schema cannot say is left out — rule objects other than CronSchedule, required_if /
 * required_with, regexes RE2 cannot run, bounds that follow the install's configuration — so a
 * client checking against it is never stricter than the server, only sometimes more lenient.
 */
final class TriggerSchema
{
    public const VERSION = 1;

    public const PATH = 'triggers/triggers.schema.json';

    /** Rules that set the value's type (Laravel's getSize() reads numbers / counts by them). */
    private const TYPES = ['string' => 'string', 'integer' => 'integer', 'numeric' => 'number', 'boolean' => 'boolean', 'array' => 'array', 'list' => 'array'];

    public function __construct(private TriggerTypes $types) {}

    /** resources/triggers/triggers.schema.json */
    public static function path(): string
    {
        return resource_path(self::PATH);
    }

    /** @return array<string, mixed> */
    public function build(): array
    {
        $types = [];
        $keys = $this->types->keys();
        sort($keys);
        foreach ($keys as $key) {
            $types[$key] = $this->typeSchema($this->types->get($key));
        }

        return [
            '$comment' => 'Generated by `php artisan triggers:schema` (App\\Triggers\\TriggerSchema) from the validation rules of the trigger types; do not edit. '
                .'Laravel semantics: required = present and not empty; integer / number / boolean accept their string forms; array = a list or a mapping, items = its elements or values; enum compares as strings.',
            'version' => self::VERSION,
            'entry' => [
                'type' => 'object',
                'required' => ['type'],
                'properties' => [
                    'enabled' => ['type' => ['boolean', 'null']],
                    'name' => ['type' => ['string', 'null'], 'pattern' => self::pattern(ProjectTrigger::NAME_PATTERN), 'maxLength' => 63],
                    'type' => ['type' => 'string'],
                ],
            ],
            'types' => $types,
        ];
    }

    /** The JSON as the file holds it (pretty, stable order, trailing newline). */
    public function render(): string
    {
        return json_encode($this->build(), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR)."\n";
    }

    /**
     * The schema of one type's config: its rules() keys, without the bounds that follow the
     * configuration (a rule that changes when every number under config('triggers') changes).
     *
     * @return array<string, mixed>
     */
    public function typeSchema(TriggerType $type): array
    {
        $rules = $type->rules();
        $varying = self::configDependent($type, $rules);

        return self::objectSchema($rules, $varying, '');
    }

    /**
     * The schema of a set of rules (keys relative to an object; dotted keys reach nested ones).
     *
     * @param  array<string, mixed>  $rules
     * @param  array<string, list<string>>  $varying  rule tokens per key that follow the configuration
     * @return array<string, mixed>
     */
    public static function objectSchema(array $rules, array $varying = [], string $prefix = ''): array
    {
        // Keys directly under this object, and the rules of their children
        $own = [];
        foreach ($rules as $key => $rule) {
            $key = (string) $key;
            [$head] = explode('.', $key, 2);
            $own[$head] ??= [];
        }
        ksort($own);

        $properties = [];
        $required = [];
        foreach (array_keys($own) as $head) {
            $children = [];
            foreach ($rules as $key => $rule) {
                $key = (string) $key;
                if (str_starts_with($key, $head.'.')) {
                    $children[substr($key, strlen($head) + 1)] = $rule;
                }
            }
            [$schema, $isRequired] = self::fieldSchema($rules[$head] ?? [], $children, $varying, $prefix.$head);
            $properties[$head] = $schema;
            if ($isRequired) {
                $required[] = $head;
            }
        }

        $out = ['type' => 'object'];
        if ($required !== []) {
            $out['required'] = $required;
        }
        $out['properties'] = $properties === [] ? new \stdClass : $properties;

        return $out;
    }

    /**
     * One field: its own rules and those of its children ("*" = every element, "sub" = a key of a
     * mapping).
     *
     * @param  array<string, mixed>  $children
     * @param  array<string, list<string>>  $varying
     * @return array{0: array<string, mixed>, 1: bool} the schema and whether the field is required
     */
    private static function fieldSchema(mixed $rule, array $children, array $varying, string $path): array
    {
        $parsed = self::parse($rule, $varying[$path] ?? []);
        $schema = self::scalarSchema($parsed, $children !== []);

        if ($children !== []) {
            $items = [];
            $props = [];
            foreach ($children as $key => $childRule) {
                if ($key === '*' || str_starts_with($key, '*.')) {
                    $items[$key === '*' ? '' : substr($key, 2)] = $childRule;
                } else {
                    $props[$key] = $childRule;
                }
            }
            if ($props !== []) {
                $nested = self::objectSchema($props, $varying, $path.'.');
                if (isset($nested['required'])) {
                    $schema['required'] = $nested['required'];
                }
                $schema['properties'] = $nested['properties'];
            }
            if ($items !== []) {
                $itemRule = $items[''] ?? [];
                unset($items['']);
                if ($items !== []) {
                    // elements that are mappings: their keys' rules
                    [$item] = self::fieldSchema($itemRule, $items, $varying, $path.'.*');
                } else {
                    [$item] = self::fieldSchema($itemRule, [], $varying, $path.'.*');
                }
                $schema['items'] = $item === [] ? new \stdClass : $item;
            }
        }

        return [$schema, $parsed['required']];
    }

    /**
     * @param  array{required: bool, nullable: bool, type: ?string, format: ?string, enum: ?list<string>, patterns: list<string>, not: list<string>, min: ?string, max: ?string, size: ?string}  $p
     * @return array<string, mixed>
     */
    private static function scalarSchema(array $p, bool $hasChildren): array
    {
        $type = $p['type'] ?? ($hasChildren ? 'array' : null);
        $schema = [];
        if ($type !== null) {
            $schema['type'] = $p['nullable'] ? [$type, 'null'] : $type;
        }
        if ($p['format'] !== null) {
            $schema['format'] = $p['format'];
        }
        if ($p['enum'] !== null) {
            $schema['enum'] = $p['enum'];
        }
        if (count($p['patterns']) === 1) {
            $schema['pattern'] = $p['patterns'][0];
        } elseif (count($p['patterns']) > 1) {
            $schema['allOf'] = array_map(fn ($pattern) => ['pattern' => $pattern], $p['patterns']);
        }
        if (count($p['not']) === 1) {
            $schema['not'] = ['pattern' => $p['not'][0]];
        } elseif (count($p['not']) > 1) {
            $schema['not'] = ['anyOf' => array_map(fn ($pattern) => ['pattern' => $pattern], $p['not'])];
        }

        // Laravel sizes: a number for integer / numeric, a count for an array, else the length
        [$minKey, $maxKey] = match ($type) {
            'integer', 'number' => ['minimum', 'maximum'],
            'array' => ['minItems', 'maxItems'],
            'string' => ['minLength', 'maxLength'],
            default => [null, null],
        };
        if ($minKey !== null) {
            $numeric = in_array($type, ['integer', 'number'], true);
            $cast = fn (string $v): int|float => $numeric && str_contains($v, '.') ? (float) $v : (int) $v;
            $min = $p['size'] ?? $p['min'];
            $max = $p['size'] ?? $p['max'];
            if ($min !== null && is_numeric($min)) {
                $schema[$minKey] = $cast($min);
            }
            if ($max !== null && is_numeric($max)) {
                $schema[$maxKey] = $cast($max);
            }
        }
        // required: not empty — a required list has an element
        if ($p['required'] && $type === 'array' && ! isset($schema['minItems'])) {
            $schema['minItems'] = 1;
        }

        return $schema;
    }

    /**
     * The parts of a rule (Laravel string, list of strings and rule objects) a schema can say.
     *
     * @param  list<string>  $skip  rule tokens left out (they follow the configuration)
     * @return array{required: bool, nullable: bool, type: ?string, format: ?string, enum: ?list<string>, patterns: list<string>, not: list<string>, min: ?string, max: ?string, size: ?string}
     */
    public static function parse(mixed $rule, array $skip = []): array
    {
        $out = ['required' => false, 'nullable' => false, 'type' => null, 'format' => null, 'enum' => null, 'patterns' => [], 'not' => [], 'min' => null, 'max' => null, 'size' => null];

        foreach (self::tokens($rule) as $token) {
            if ($token instanceof CronSchedule) {
                $out['format'] = 'cron';

                continue;
            }
            if ($token instanceof In) {
                $out['enum'] = self::inValues((string) $token);

                continue;
            }
            if (! is_string($token) || in_array($token, $skip, true)) {
                continue; // other rule objects and closures: the server's only
            }

            [$name, $params] = ValidationRuleParser::parse($token);
            $name = strtolower((string) preg_replace('/(?<!^)[A-Z]/', '_$0', (string) $name));
            switch ($name) {
                case 'required':
                    $out['required'] = true;
                    break;
                case 'nullable':
                    $out['nullable'] = true;
                    break;
                case 'string': case 'integer': case 'numeric': case 'boolean': case 'array': case 'list':
                    $out['type'] = self::TYPES[$name];
                    break;
                case 'in':
                    $out['enum'] = array_values(array_map('strval', $params));
                    break;
                case 'min': case 'max': case 'size':
                    $out[$name] = isset($params[0]) ? (string) $params[0] : null;
                    break;
                case 'regex':
                    if (($pattern = self::pattern((string) ($params[0] ?? ''))) !== null) {
                        $out['patterns'][] = $pattern;
                    }
                    break;
                case 'not_regex':
                    if (($pattern = self::pattern((string) ($params[0] ?? ''))) !== null) {
                        $out['not'][] = $pattern;
                    }
                    break;
                case 'timezone':
                    $out['format'] = 'timezone';
                    break;
            }
        }

        return $out;
    }

    /**
     * The rule as a list: a Laravel pipe string is split as the validator splits it (a regex rule
     * given as the whole string stays one).
     *
     * @return list<mixed>
     */
    private static function tokens(mixed $rule): array
    {
        if (is_string($rule)) {
            return preg_match('/^(not_)?regex:/i', $rule) ? [$rule] : explode('|', $rule);
        }
        if (! is_array($rule)) {
            return [$rule];
        }

        $out = [];
        foreach ($rule as $item) {
            array_push($out, ...(is_string($item) && ! preg_match('/^(not_)?regex:/i', $item) ? explode('|', $item) : [$item]));
        }

        return $out;
    }

    /** @return list<string> the values of Rule::in (in:"a","b") */
    private static function inValues(string $rule): array
    {
        $list = substr($rule, 3);

        return $list === '' ? [] : array_map('strval', str_getcsv($list, ',', '"', ''));
    }

    /**
     * A PHP regex (/…/flags) as an RE2 pattern; null when RE2 cannot run it (lookarounds,
     * backreferences, possessive or atomic groups, \K \R \h \G \Z) or a flag has no RE2 form.
     * PCRE's $ also matches before a final newline (no D flag): the pattern keeps that.
     */
    public static function pattern(string $regex): ?string
    {
        if (strlen($regex) < 2) {
            return null;
        }
        $delimiter = $regex[0];
        $closing = ['(' => ')', '[' => ']', '{' => '}', '<' => '>'][$delimiter] ?? $delimiter;
        $end = strrpos($regex, $closing);
        if ($end === false || $end === 0) {
            return null;
        }
        $body = substr($regex, 1, $end - 1);
        $flags = substr($regex, $end + 1);
        if ($delimiter !== '/' && $closing === $delimiter) {
            $body = str_replace('\\'.$delimiter, $delimiter, $body);
        }

        if (preg_match('/\(\?[=!<>|]|\(\?P=|\\\\[KRhGZ]|\\\\[1-9]|[*+?}]\+/', $body)) {
            return null;
        }

        // i m s have RE2 forms; u and D change nothing here; any other flag: left to the server
        if (preg_match('/[^imsuD]/', $flags)) {
            return null;
        }
        $inline = (string) preg_replace('/[uD]/', '', $flags);

        // PCRE: "$" at the end also matches before a final "\n" unless D is set
        if (! str_contains($flags, 'D') && ! str_contains($flags, 'm') && preg_match('/(?<!\\\\)\$$/', $body)) {
            $body = substr($body, 0, -1).'\n?$';
        }

        return ($inline !== '' ? '(?'.$inline.')' : '').$body;
    }

    /**
     * Rule tokens of $rules that change with the configuration: the type's rules built again with
     * every number under config('triggers') raised by one; a token that differs is the install's
     * (e.g. max_body_kb up to TRIGGERS_WEBHOOK_MAX_BODY_KB), not the type's.
     *
     * @param  array<string, mixed>  $rules
     * @return array<string, list<string>>
     */
    private static function configDependent(TriggerType $type, array $rules): array
    {
        $original = config('triggers');
        if (! is_array($original)) {
            return [];
        }

        $bump = function (mixed $value) use (&$bump): mixed {
            if (is_array($value)) {
                return array_map($bump, $value);
            }

            return is_int($value) || (is_string($value) && ctype_digit($value)) ? ((int) $value) + 1 : $value;
        };

        config(['triggers' => $bump($original)]);
        try {
            $bumped = $type->rules();
        } finally {
            config(['triggers' => $original]);
        }

        $varying = [];
        foreach ($rules as $key => $rule) {
            $before = array_filter(self::tokens($rule), 'is_string');
            $after = array_filter(self::tokens($bumped[$key] ?? []), 'is_string');
            $changed = array_values(array_diff($before, $after));
            if ($changed !== []) {
                $varying[(string) $key] = $changed;
            }
        }

        return $varying;
    }
}
