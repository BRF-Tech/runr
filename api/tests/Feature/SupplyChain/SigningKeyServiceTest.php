<?php

namespace Tests\Feature\SupplyChain;

use App\Events\SupplyChainAuditEvent;
use App\Jobs\GenerateSigningKeyJob;
use App\Models\RegionSupplyChainSetting;
use App\Services\SupplyChain\AdmissionPolicyService;
use App\Services\SupplyChain\SigningKeyService;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Bus;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Event;
use Tests\Concerns\FakesSupplyChainCluster;
use Tests\TestCase;

/**
 * Region key generation in the cluster: RBAC + password Secret + keygen Job, the key Secret read
 * back into the API's encrypted copy, cleanup, failure, rotation.
 */
class SigningKeyServiceTest extends TestCase
{
    use FakesSupplyChainCluster, RefreshDatabase;

    protected function setUp(): void
    {
        parent::setUp();
        $this->fakeSupplyChainCluster();
        Event::fake([SupplyChainAuditEvent::class]);
        $this->app->bind(SigningKeyService::class, fn () => new class extends SigningKeyService
        {
            protected function sleep(int $seconds): void {}
        });
    }

    protected function tearDown(): void
    {
        $this->tearDownSupplyChain();
        parent::tearDown();
    }

    /** The Secret cosign wrote (after the Job ran). */
    private function keySecret(string $pub): array
    {
        return ['metadata' => ['name' => 'runr-cosign-key'], 'data' => [
            'cosign.key' => base64_encode("-----BEGIN ENCRYPTED SIGSTORE PRIVATE KEY-----\nZZZZ\n-----END ENCRYPTED SIGSTORE PRIVATE KEY-----\n"),
            'cosign.pub' => base64_encode($pub),
            'cosign.password' => base64_encode('generated-password'),
        ]];
    }

    public function test_keygen_runs_in_the_region_and_stores_an_encrypted_copy(): void
    {
        $region = $this->scRegion();
        $pub = self::scPublicKey();
        $this->k8sGet['/api/v1/namespaces/runr-supply-chain/secrets/runr-cosign-key'] = $this->keySecret($pub);

        $settings = app(SigningKeyService::class)->runKeygen($region, rotate: false);

        // RBAC limited to Secrets of the supply-chain namespace
        $this->assertNotEmpty($this->scCalls('PATCH', '/apis/rbac.authorization.k8s.io/v1/namespaces/runr-supply-chain/roles/runr-supply-chain-keygen'));
        $this->assertNotEmpty($this->scCalls('PATCH', '/api/v1/namespaces/runr-supply-chain/serviceaccounts/runr-supply-chain-keygen'));
        // Password Secret generated by the API, consumed by the Job
        $password = $this->scCalls('PATCH', '/api/v1/namespaces/runr-supply-chain/secrets/runr-cosign-keygen')[0]['body'];
        $this->assertSame(48, strlen(base64_decode($password['data']['password'])));
        $job = $this->scCreated('/apis/batch/v1/namespaces/runr-supply-chain/jobs');
        $this->assertSame(['keygen'], $job['spec']['template']['spec']['containers'][0]['args']);

        $this->assertSame('ready', $settings->signing_status);
        $this->assertSame(SigningKeyService::fingerprint($pub), $settings->signing_key_fingerprint);
        $this->assertSame(trim($pub)."\n", $settings->signing_public_key);
        $this->assertSame('generated-password', $settings->fresh()->signing_key_password);
        $raw = DB::table('region_supply_chain_settings')->value('signing_private_key');
        $this->assertStringNotContainsString('SIGSTORE', $raw, 'encrypted at rest');

        // Fingerprint annotation on the Secret, then cleanup of everything temporary
        $patch = collect($this->scCalls('PATCH', '/secrets/runr-cosign-key'))->first(fn ($c) => isset($c['body']['metadata']['annotations']));
        $this->assertSame($settings->signing_key_fingerprint, $patch['body']['metadata']['annotations']['runr.sh/key-fingerprint']);
        foreach (['/secrets/runr-cosign-keygen', '/rolebindings/runr-supply-chain-keygen', '/roles/runr-supply-chain-keygen', '/serviceaccounts/runr-supply-chain-keygen'] as $path) {
            $this->assertNotEmpty($this->scCalls('DELETE', $path), "{$path} removed");
        }

        Event::assertDispatched(SupplyChainAuditEvent::class, fn ($e) => $e->action === 'region.signing_key.generated' && $e->details['fingerprint'] === $settings->signing_key_fingerprint);
    }

    public function test_a_failed_keygen_job_reports_its_reason(): void
    {
        $region = $this->scRegion();
        $this->jobStatus = ['failed' => 1];
        $this->podLog = 'RUNR_STEP keygen failed '.base64_encode('secrets is forbidden')."\nRUNR_DONE\n";
        $this->k8sGet['/api/v1/namespaces/runr-supply-chain/secrets/runr-cosign-key'] = null;

        try {
            app(SigningKeyService::class)->runKeygen($region, rotate: false);
            $this->fail('expected the keygen to fail');
        } catch (\RuntimeException $e) {
            $this->assertStringContainsString('secrets is forbidden', $e->getMessage());
        }

        $this->assertNotEmpty($this->scCalls('DELETE', '/secrets/runr-cosign-keygen'), 'cleanup after a failure too');
    }

    public function test_a_failed_job_marks_the_settings(): void
    {
        $region = $this->scRegion();
        $this->scSettings($region, ['signing_status' => 'generating']);

        (new GenerateSigningKeyJob($region))->failed(new \RuntimeException('cluster unreachable'));

        $settings = RegionSupplyChainSetting::forRegion($region);
        $this->assertSame('failed', $settings->signing_status);
        $this->assertSame('cluster unreachable', $settings->signing_message);

        // A failed rotation keeps the previous key usable
        $this->scSigningReady($region, ['signing_status' => 'generating']);
        (new GenerateSigningKeyJob($region, rotate: true))->failed(new \RuntimeException('boom'));
        $this->assertSame('ready', RegionSupplyChainSetting::forRegion($region)->signing_status);
    }

    public function test_rotation_retires_the_previous_key_and_updates_admission(): void
    {
        $region = $this->scRegion();
        $old = $this->scSigningReady($region, ['admission_status' => 'ready']);
        Bus::fake([GenerateSigningKeyJob::class]);

        app(SigningKeyService::class)->generate($region, rotate: true);

        $settings = RegionSupplyChainSetting::forRegion($region);
        $this->assertSame('generating', $settings->signing_status);
        $this->assertSame($old->signing_key_fingerprint, $settings->signing_retired_keys[0]['fingerprint']);
        $this->assertCount(1, $settings->trustedKeys(), 'current and retired key are the same until the new one is stored');

        // The job: new key, then the admission policy is synced
        $newPub = self::scPublicKey();
        $this->k8sGet['/api/v1/namespaces/runr-supply-chain/secrets/runr-cosign-key'] = $this->keySecret($newPub);
        $admission = $this->mock(AdmissionPolicyService::class);
        $admission->shouldReceive('syncPolicies')->once();

        (new GenerateSigningKeyJob($region, rotate: true))->handle(app(SigningKeyService::class), $admission);

        $settings = RegionSupplyChainSetting::forRegion($region);
        $this->assertSame(SigningKeyService::fingerprint($newPub), $settings->signing_key_fingerprint);
        $this->assertEqualsCanonicalizing([$settings->signing_key_fingerprint, $old->signing_key_fingerprint], $settings->trustedFingerprints());
        Event::assertDispatched(SupplyChainAuditEvent::class, fn ($e) => $e->action === 'region.signing_key.rotated');
    }

    public function test_fingerprint_is_the_sha256_of_the_der_key(): void
    {
        $pub = self::scPublicKey();
        $der = base64_decode(preg_replace('/-----[^-]+-----|\s+/', '', $pub));

        $this->assertSame(hash('sha256', $der), SigningKeyService::fingerprint($pub));
        $this->assertSame(SigningKeyService::fingerprint($pub), SigningKeyService::fingerprint(str_replace("\n", "\r\n", $pub)));
    }
}
